"""Finite extraction-and-review ledger layered on the existing four-regime harness.

Candidate relations are NOT generated by a model here: they must be supplied by
a caller with explicit source spans, independent reviewer verdicts and measured
work durations. The K/B/C/T tags are experimental role labels, NOT a claim to
implement or validate the entire APX 12G formal grammar. No reviews are
authenticated and no checks can grant ADMIT.
"""
from __future__ import annotations

import math
from typing import Any

from four_regime_experiment import run_regime_contrast
from semantic_codex import CodexError
from store import digest

SCHEMA="qualityrag.relation-review-experiment/v1.1"
ROLES={"K","B","C","T"}
VERDICTS={"SUPPORTED","REJECTED","UNCERTAIN"}
MAX_CANDIDATES=100


def _time(value: Any, label: str) -> float:
    if type(value) not in (int,float) or not math.isfinite(value) or value<0 or value>3_600_000:
        raise CodexError(label+" must be nonnegative finite milliseconds")
    return float(value)


def run_candidate_review(manifest: dict, candidate_ledger: dict, *,
                         principal: str, authorize_source, repetitions: int=2) -> dict:
    if (not isinstance(candidate_ledger,dict) or
            set(candidate_ledger)!={"schema","candidate_relations","witness_reviews","human_review_authentication"}
            or candidate_ledger["schema"]!="qualityrag.relation-review-input/v1.1"
            or candidate_ledger["human_review_authentication"]!="UNVERIFIED"):
        raise CodexError("Invalid unverified relation review ledger")
    candidates=candidate_ledger["candidate_relations"]
    witnesses=candidate_ledger["witness_reviews"]
    if (not isinstance(candidates,list) or len(candidates)>MAX_CANDIDATES
            or not isinstance(witnesses,list) or len(witnesses)>MAX_CANDIDATES):
        raise CodexError("Candidate inventories must be bounded")
    if not isinstance(manifest,dict) or not isinstance(manifest.get("sources"),list):
        raise CodexError("Missing base experiment source inventory")
    sources={s.get("id"):s.get("text") for s in manifest["sources"] if isinstance(s,dict)}
    if len(sources)!=len(manifest["sources"]):
        raise CodexError("Duplicate/malformed source identifiers")
    expected={(e["from"],e["to"],e["relation"]) for e in manifest.get("relations",[])}
    input_edges=set()
    by_verdict={v:0 for v in VERDICTS}
    tag_counts={v:0 for v in ROLES}
    processing=review=0.0
    evidence_failures=[]
    for i,item in enumerate(candidates):
        if not isinstance(item,dict) or set(item)!={
            "from","to","relation","role","quoted_evidence","evidence_source",
            "review_verdict","extraction_ms","review_ms"}:
            raise CodexError("Incomplete relation candidate at index "+str(i))
        key=(item["from"],item["to"],item["relation"])
        if key in input_edges or key[0] not in sources or key[1] not in sources:
            raise CodexError("Duplicate candidate or unrecognized source")
        input_edges.add(key)
        if item["role"] not in ROLES or item["review_verdict"] not in VERDICTS:
            raise CodexError("Invalid typed role or reviewer verdict")
        quote=item["quoted_evidence"]
        source=item["evidence_source"]
        if (source not in sources or not isinstance(quote,str) or
                not 1<=len(quote)<=200 or quote not in sources[source]):
            evidence_failures.append({"candidate_index":i,"status":"SOURCE_QUOTE_NOT_FOUND"})
        processing+=_time(item["extraction_ms"],"extraction_ms")
        review+=_time(item["review_ms"],"review_ms")
        by_verdict[item["review_verdict"]]+=1
        tag_counts[item["role"]]+=1
    witness_keys=set()
    witness_ms=0.0
    for entry in witnesses:
        if (not isinstance(entry,dict) or
                set(entry)!={"target","source","review_verdict","review_ms"} or
                entry["target"] not in sources or entry["source"] not in sources
                or entry["review_verdict"] not in VERDICTS):
            raise CodexError("Invalid witness review entry")
        key=(entry["target"],entry["source"])
        if key in witness_keys:
            raise CodexError("Duplicate witness review")
        witness_keys.add(key)
        witness_ms+=_time(entry["review_ms"],"witness review time")
    if input_edges != expected:
        raise CodexError("Relation candidate inventory must cover exactly declared graph edges")
    expected_witness={(w["target"],w["source"]) for w in manifest.get("witnesses",[])}
    if witness_keys!=expected_witness:
        raise CodexError("Witness review inventory must exactly match source graph")
    # Every human verdict is caller-supplied; even SUPPORTED is not authenticated.
    # Structural quote checks prove only string presence, never proposition truth.
    experiment=run_regime_contrast(manifest,repetitions=repetitions,
                                    principal=principal,authorize_source=authorize_source)
    apparently_supported=sum(c["review_verdict"]=="SUPPORTED" for c in candidates)
    contradicted=sum(c["review_verdict"]=="REJECTED" for c in candidates)
    unknown=sum(c["review_verdict"]=="UNCERTAIN" for c in candidates)
    return {
        "schema":SCHEMA,
        "base_regime_experiment":experiment,
        "candidate_ledger_fingerprint":digest(candidate_ledger),
        "typed_role_distribution":tag_counts,
        "candidate_counts":{"submitted":len(candidates),"review_supported_unverified":apparently_supported,
                            "review_rejected":contradicted,"review_uncertain":unknown,
                            "unlocated_quotes":len(evidence_failures)},
        "review_verdict_counts":by_verdict,
        "quote_anchor_failures":evidence_failures,
        "observed_costs_ms":{"relation_extraction_caller_supplied":processing,
                             "relation_review_caller_supplied":review,
                             "witness_review_caller_supplied":witness_ms,
                             "total_caller_supplied":processing+review+witness_ms},
        "review_time_basis":"CALLER_SUPPLIED_NOT_INSTRUMENTED_OR_AUTHENTICATED",
        "typed_roles":"EXPERIMENTAL_K_B_C_T_LABELS_NOT_FULL_12G_GRAMMAR",
        "meaning_preservation":"NOT_VERIFIED",
        "false_positive_rate":"NOT_ESTABLISHED_INDEPENDENT_GROUND_TRUTH_REQUIRED",
        "automatic_relation_discovery":"NOT_PERFORMED",
        "packspec_evaluation":"NOT_PERFORMED",
        "source_authenticity":"UNVERIFIED",
        "admission":"INCONCLUSIVE","can_generate":False,
    }
